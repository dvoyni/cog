// Command generate writes the ECS code that repeats per term count: Query1
// to Query8 with their rows. Run it with go generate in the ecs directory.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"strings"
	"text/template"
)

const maxArity = 8

const header = `// Code generated by internal/generate; DO NOT EDIT.

package ecs

import (
	"iter"
	"unsafe"

	"github.com/dvoyni/cog/kernel"
)
`

var queryTemplate = template.Must(template.New("query").Parse(`
// Query{{.N}} walks the entities of world W holding every one of its {{.N}}
// terms. A pointer term *T writes T's store and yields the row's address; a
// value term T reads it and yields a copy; With[T] and Without[T] filter and
// yield nothing.
type Query{{.N}}[W WorldID, {{.Types}} any] struct {
	terms  [{{.N}}]term
	writes uint8
}

// Row{{.N}} is one entity's terms, yielded by Query{{.N}}.All.
type Row{{.N}}[{{.Types}} any] struct {
	addresses [{{.N}}]unsafe.Pointer
	writes    uint8
}

// Declare declares a lock on each term's store and a read on world W.
func (Query{{.N}}[W, {{.Types}}]) Declare(access *kernel.Access) Query{{.N}}[W, {{.Types}}] {
	w := access.Read[*world[W]]().Get()
	var q Query{{.N}}[W, {{.Types}}]
{{- range .Terms}}
	q.terms[{{.Index}}] = declareTerm[W, {{.Type}}](access, w)
{{- end}}
	q.writes = declareQuery(q.terms[:])
	return q
}

// All walks the entities holding every term, yielding each with its row.
// It goes backwards from the smallest store's last row, so removing the
// current entity from any store is safe.
func (q Query{{.N}}[W, {{.Types}}]) All() iter.Seq2[Entity, Row{{.N}}[{{.Types}}]] {
	return func(yield func(Entity, Row{{.N}}[{{.Types}}]) bool) {
		row := Row{{.N}}[{{.Types}}]{writes: q.writes}
		driver := driverOf(q.terms[:])
		for r := driver.len() - 1; r >= 0; r-- {
			e := *driver.owners.At(r)
			if match(q.terms[:], row.addresses[:], e) && !yield(e, row) {
				return
			}
		}
	}
}

// Get returns the row's terms.
func (r Row{{.N}}[{{.Types}}]) Get() ({{.Types}}) {
	return {{range $i, $t := .Terms}}{{if $i}}, {{end}}termValue[{{$t.Type}}](r.addresses[{{$t.Index}}], r.writes&(1<<{{$t.Index}}) != 0){{end}}
}
`))

type termData struct {
	Index int
	Type  string
}

type arityData struct {
	N     int
	Types string
	Terms []termData
}

func makeArity(n int) arityData {
	data := arityData{N: n}
	var types []string
	for i := range n {
		types = append(types, fmt.Sprintf("T%d", i+1))
		data.Terms = append(data.Terms, termData{
			Index: i,
			Type:  types[i],
		})
	}
	data.Types = strings.Join(types, ", ")
	return data
}

func main() {
	var out bytes.Buffer
	out.WriteString(header)
	for n := 1; n <= maxArity; n++ {
		if err := queryTemplate.Execute(&out, makeArity(n)); err != nil {
			panic(err)
		}
	}
	source, err := format.Source(out.Bytes())
	if err != nil {
		panic(fmt.Sprintf("%v\n%s", err, out.Bytes()))
	}
	if err := os.WriteFile("query_gen.go", source, 0o644); err != nil {
		panic(err)
	}
}

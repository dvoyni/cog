type termData struct {
	Index int
	Type  string
}

type arityData struct {
	N     int
	Types string
	Terms []termData
}

func makeArity(n int) arityData {
	data := arityData{N: n}
	var types []string
	for i := range n {
		types = append(types, fmt.Sprintf("T%d", i+1))
		data.Terms = append(data.Terms, termData{
			Index: i,
			Type:  types[i],
		})
	}
	data.Types = strings.Join(types, ", ")
	return data
}

func main() {
	generate("query_gen.go", queryTemplate)
	generate("deltaquery_gen.go", deltaQueryTemplate)
}

// generate writes file: the header, then t executed for every arity.
func generate(file string, t *template.Template) {
	var out bytes.Buffer
	out.WriteString(header)
	for n := 1; n <= maxArity; n++ {
		if err := t.Execute(&out, makeArity(n)); err != nil {
			panic(err)
		}
	}
	source, err := format.Source(out.Bytes())
	if err != nil {
		panic(fmt.Sprintf("%v\n%s", err, out.Bytes()))
	}
	if err := os.WriteFile(file, source, 0o644); err != nil {
		panic(err)
	}
}

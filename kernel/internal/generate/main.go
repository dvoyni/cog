// Command generate writes the kernel code that repeats per parameter count:
// Configurator.RegisterTask0 to RegisterTask8. Run it with go generate in the
// kernel directory.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"text/template"
)

const maxParameters = 8

const header = "// Code generated by internal/generate; DO NOT EDIT.\n\npackage kernel\n"

var registerTemplate = template.Must(template.New("register").Parse(`
// RegisterTask{{.N}} registers function as a task, as RegisterTask does; {{.N}}
// is how many parameters follow its arg. Each parameter is a Parameter,
// declared once, here, from its zero value; the body only calls function. A
// task that also calls another directly uses RegisterTask and Access.Use.
//
// It is a composition error, and panics, for function to be nil, or for what
// RegisterTask refuses.
func (c *Configurator) RegisterTask{{.N}}[A, B any{{range .Parameters}}, {{.Type}} Parameter[{{.Type}}]{{end}}](function func(kernel *Kernel, arg A{{range .Parameters}}, {{.Name}} {{.Type}}{{end}}) B) *Task[A, B] {
	if function == nil {
		panic("kernel: registering a nil task function")
	}
	return c.RegisterTask(func(access *Access) TaskBody[A, B] {
{{- range .Parameters}}
		{{.Name}} := (*new({{.Type}})).Declare(access)
{{- end}}
		return func(kernel *Kernel, arg A) B {
			return function(kernel, arg{{range .Parameters}}, {{.Name}}{{end}})
		}
	})
}
`))

type parameter struct {
	Type string
	Name string
}

type arity struct {
	N          int
	Parameters []parameter
}

func main() {
	var out bytes.Buffer
	out.WriteString(header)
	for n := range maxParameters + 1 {
		data := arity{N: n}
		for i := range n {
			data.Parameters = append(data.Parameters, parameter{Type: fmt.Sprintf("P%d", i+1), Name: fmt.Sprintf("p%d", i+1)})
		}
		if err := registerTemplate.Execute(&out, data); err != nil {
			panic(err)
		}
	}
	source, err := format.Source(out.Bytes())
	if err != nil {
		panic(fmt.Sprintf("%v\n%s", err, out.Bytes()))
	}
	if err := os.WriteFile("configurator_gen.go", source, 0o644); err != nil {
		panic(err)
	}
}
